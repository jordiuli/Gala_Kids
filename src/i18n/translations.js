const LETTER_COLORS = ["#e63946", "#fbbf24", "#2563eb", "#16a34a", "#f97316"];

export function colorizeWord(word) {
  return word.split("").map((letter, i) => ({
    letter,
    color: LETTER_COLORS[i % LETTER_COLORS.length],
  }));
}

